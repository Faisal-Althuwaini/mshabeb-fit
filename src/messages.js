function getRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getMotivational() {
  return getRandom(MOTIVATIONAL_MESSAGES);
}

function getTrendMessage(weekAvg, lastWeekAvg) {
  if (weekAvg == null || lastWeekAvg == null) return getMotivational();
  const diff = weekAvg - lastWeekAvg;
  if (diff < -0.1) return getRandom(TREND_DOWN);
  if (diff > 0.1) return getRandom(TREND_UP);
  return getRandom(TREND_SAME);
}

